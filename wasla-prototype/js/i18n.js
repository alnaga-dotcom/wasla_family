  const STORAGE_KEY = 'wasla_lang';

  const I18n = {
    current: 'ar',
    set(lang) {
      if (!i18n[lang]) lang = 'ar';
      this.current = lang;
      try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
      document.documentElement.lang = lang;
      document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
      document.title = this.t('app.title');
      this.apply();
    },
    t(key, vars) {
      let text = i18n[this.current]?.[key] ?? i18n.ar[key] ?? key;
      if (vars) {
        Object.keys(vars).forEach((k) => {
          text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
        });
      }
      return text;
    },
    apply() {
      document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.setAttribute('placeholder', this.t(key));
      });
      document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        const text = this.t(key);
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          if (el.hasAttribute('placeholder')) el.setAttribute('placeholder', text);
          else el.value = text;
        } else {
          el.textContent = text;
        }
      });
      document.querySelectorAll('[data-i18n-title]').forEach((el) => {
        el.setAttribute('title', this.t(el.getAttribute('data-i18n-title')));
      });
      document.querySelectorAll('select[data-i18n-options]').forEach((sel) => {
        const keys = (sel.getAttribute('data-i18n-options') || '').split(',').map((s) => s.trim()).filter(Boolean);
        Array.from(sel.children).forEach((opt, idx) => {
          if (keys[idx] && opt.value !== '') opt.textContent = this.t(keys[idx]);
        });
      });
    },
    init() {
      let saved = 'ar';
      try { saved = localStorage.getItem(STORAGE_KEY) || 'ar'; } catch (e) {}
      this.set(saved);
    }
  };

  function t(key, vars) { return I18n.t(key, vars); }
  function toLocalizedDigits(str) {
    if (I18n.current === 'ar') {
      const map = { '0': '٠', '1': '١', '2': '٢', '3': '٣', '4': '٤', '5': '٥', '6': '٦', '7': '٧', '8': '٨', '9': '٩' };
      return String(str || '').replace(/\d/g, (d) => map[d] || d);
    }
    return String(str || '');
  }

  window.I18n = I18n;
  window.t = t;
  window.toLocalizedDigits = toLocalizedDigits;

  document.addEventListener('DOMContentLoaded', () => I18n.init());

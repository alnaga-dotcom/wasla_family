let created = 0;
let failed = 0;

for (const post of posts) {
  try {
    const res = await fetch(`${BASE}/admin/posts`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'x-admin-key': KEY },
      body: JSON.stringify(post),
    });
    const data = await res.json().catch(() => ({}));
    if (res.ok && data.ok) {
      console.log(`OK    ${post.slug} (id=${data.id})`);
      created++;
    } else {
      console.log(`FAIL  ${post.slug} [${res.status}] ${JSON.stringify(data)}`);
      failed++;
    }
  } catch (err) {
    console.log(`ERR   ${post.slug} ${err.message}`);
    failed++;
  }
}

console.log(`\nDone: ${created} created, ${failed} failed.`);
